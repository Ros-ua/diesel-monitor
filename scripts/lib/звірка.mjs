/**
 * Звірка джерел цін між собою: підміну видно не всередині таблиці, а збоку.
 *
 * ⚠️ 26.09.2026 (аудит). Уся оборона парсера — «чи правильно я прочитав
 * таблицю». Вона не бачить підміни, коли сама таблиця виглядає правильно:
 * шапка впізнана, числа схожі на ціни, межа 5..500 мовчить. Саме так з 11.09
 * по 21.09.2026 (сім днів) у history.json лягли ціни мереж, зсунуті на колонку:
 * А-95 під підписом А-95+, А-92 під А-95, дизель під А-92, а під «Газ» —
 * дизель. Медіана «газу» по мережах вийшла 98,70 при середній ціні газу 44,09
 * (+124%), медіана «дизеля» 82 при середній 97,92 (−16%). Сторінка середніх
 * цін увесь цей час була правильна — порівняти з нею означало побачити біду
 * в перший же день.
 *
 * Правило: кожне джерело (середні ціни, мережі /tm/, області /reg/, матриця
 * /detail/) дає по кожному виду пального одне число — саму ціну або медіану.
 * Джерело, яке не сходиться з БІЛЬШІСТЮ інших хоч по одному виду, знімається
 * цілком: зсув колонок псує всі види одразу, і рятувати «вцілілі» не можна.
 * Коли більшості немає (два джерела розійшлися, або лишилось одне), суддею стає
 * попередня середня ціна з latest.json — з ширшим допуском, бо ціна за добу
 * справді стрибає (+13,8% 18.03.2026). Немає й судді — не знімаємо нікого.
 *
 * Функція чиста: ні мережі, ні файлів — її перевіряють пробами.
 */
import { median } from './minfin.mjs';

export const ВИДИ = ['a95p', 'a95', 'a92', 'dp', 'gas'];

/**
 * Розбіжність медіан, за якою джерела вже не сходяться. На справжніх днях
 * history.json (70 днів із картою мереж) найбільша розбіжність медіани мереж
 * із середньою — 3,7% (газ), областей — 1%. Зсув колонок дає 15–125%.
 */
export const ДОПУСК = 0.08;
/** Допуск проти ВЧОРАШНЬОЇ середньої — тільки коли більшості немає. */
export const ДОПУСК_ДО_ВЧОРА = 0.15;
/** Менше значень — медіана нічого не доводить, вид не звіряємо. */
const МІНІМУМ_ЗНАЧЕНЬ = 3;

function медіани(набір) {
  if (!набір) return null;
  const out = {};
  for (const вид of ВИДИ) {
    const vs = Object.values(набір).map(ц => ц?.[вид]).filter(v => Number.isFinite(v));
    if (vs.length >= МІНІМУМ_ЗНАЧЕНЬ) out[вид] = median(vs);
  }
  return out;
}

const згода = (а, б, допуск) => Math.abs(а / б - 1) <= допуск;

/**
 * @param {object} д
 * @param {object|null} д.середні     averages.avg  — { dp: 98.4, ... }
 * @param {object|null} д.мережі      /tm/          — { ОККО: { dp, ... }, ... }
 * @param {object|null} д.області     /reg/         — { Вінницька: { dp, ... }, ... }
 * @param {object|null} д.матриця     /detail/      — національні медіани мереж
 * @param {object|null} [д.вчора]     avg із попереднього latest.json
 * @returns {{ зняти: string[], причини: string[] }}
 */
export function звіритиДжерела({ середні, мережі, області, матриця, вчора = null }) {
  const голоси = {
    середні: середні ?? null,
    мережі: медіани(мережі),
    області: медіани(області),
    матриця: медіани(матриця),
  };
  const зняти = new Set();
  const причини = [];
  const суддя = вид => (Number.isFinite(вчора?.[вид]) ? вчора[вид] : null);
  const живі = вид => Object.entries(голоси)
    .filter(([імя, г]) => !зняти.has(імя) && г && Number.isFinite(г[вид]))
    .map(([імя, г]) => [імя, г[вид]]);
  const зняти1 = (імя, вид, v, є) => {
    зняти.add(імя);
    const з = є.filter(([інше]) => інше !== імя)
      .map(([інше, w]) => `${інше} ${w.toFixed(2)}`).join(', ');
    const с = суддя(вид);
    причини.push(`${імя}: ${вид} ${v.toFixed(2)} не сходиться (${з || 'нема з чим'}` +
      `${с !== null ? `; вчора ${с.toFixed(2)}` : ''})`);
  };

  // 1. Більшість. Знятий голос більше не голосує — тому по колу, доки є зміни:
  //    джерело, що розійшлося по дизелю, не повинно зривати більшість по газу.
  for (let змінилось = true; змінилось; ) {
    змінилось = false;
    for (const вид of ВИДИ) {
      const є = живі(вид);
      if (є.length < 2) continue;
      const уБільшості = ([імя, v]) =>
        (є.filter(([інше, w]) => інше !== імя && згода(v, w, ДОПУСК)).length + 1) * 2 > є.length;
      if (!є.some(уБільшості)) continue;              // більшості немає — крок 2
      for (const г of є) {
        if (!уБільшості(г)) { зняти1(г[0], вид, г[1], є); змінилось = true; }
      }
    }
  }

  // 2. Більшості немає (два джерела розійшлися, або лишилось одне): суддя —
  //    вчорашня середня. Без судді не знімаємо нікого: вирішувати нема чим.
  for (const вид of ВИДИ) {
    const є = живі(вид);
    const с = суддя(вид);
    if (!є.length || с === null) continue;
    const більшість = є.length >= 2 && є.some(([імя, v]) =>
      (є.filter(([інше, w]) => інше !== імя && згода(v, w, ДОПУСК)).length + 1) * 2 > є.length);
    if (більшість) continue;
    for (const [імя, v] of є) if (!згода(v, с, ДОПУСК_ДО_ВЧОРА)) зняти1(імя, вид, v, є);
  }
  return { зняти: [...зняти], причини };
}
