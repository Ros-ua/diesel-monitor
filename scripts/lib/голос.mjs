/**
 * Текст озвучки Reels (~25 слів на 12-секундний ролик). Числа округлюємо —
 * «дев'яносто два» звучить, «дев'яносто два кома вісімдесят один» — ні.
 *
 * ⚠️ Винесено з reel-voice.mjs (той запускає озвучку при імпорті, і проба не
 * могла покликати текст). Дві неправди, слово Роса 26.09 «Почини все три»:
 *  - при нульовій зміні голос казав «подешевшав» (up = diff > 0);
 *  - при рості 0,2% казав «на 1 відсоток» (Math.max(1, …)).
 */
const plural = (n, one, few, many) => {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
};

export function текстГолосу(meta) {
  const name = { dp: 'Дизель', a95: 'Бензин А-95', a95p: 'Бензин А-95 плюс', a92: 'Бензин А-92', gas: 'Автогаз' }[meta.fuel] ?? 'Пальне';
  const price = Math.round(meta.last);
  const гривень = plural(price, 'гривня', 'гривні', 'гривень');
  const period =
    meta.months >= 12 ? 'за рік'
    : meta.months <= 1 ? 'за місяць'
    : `за ${meta.months} ${plural(meta.months, 'місяць', 'місяці', 'місяців')}`;
  const відсотків = Math.abs(meta.pct);

  // ціна не зрушила — не кажемо ні «подорожчав», ні «подешевшав»
  if (meta.diff === 0 || відсотків < 0.05) {
    return (
      `${name} в Україні ${period} тримається на ${price} ${гривень} за літр. ` +
      `Куди рухається ціна — дивись на Дизель Моніторі.`
    );
  }
  const up = meta.diff > 0;
  const скільки = відсотків < 0.5
    ? 'менше ніж на відсоток'
    : `на ${Math.round(відсотків)} ${plural(Math.round(відсотків), 'відсоток', 'відсотки', 'відсотків')}`;
  return (
    `${name} в Україні ${period} ${up ? 'подорожчав' : 'подешевшав'} ${скільки} — ` +
    `уже ${price} ${гривень} за літр. ` +
    `Куди рухається ціна — дивись на Дизель Моніторі.`
  );
}
