const FUEL_TAGS = {
  dp: 'дизель',
  a95p: 'бензин',
  a95: 'бензин',
  a92: 'бензин',
  gas: 'автогаз',
};

const MAX = 5;

/**
 * @param {object} o
 * @param {string} [o.fuel]     ключ пального, про яке пост
 * @param {string} [o.region]   назва області, якщо пост про неї
 * @param {number} [o.change]   зміна ціни (для тега події)
 * @param {boolean} [o.news]    пост-новина
 */
export function pickHashtags({ fuel, region, change, news } = {}) {
  const tags = [];
  const add = t => {
    const clean = String(t).replace(/[^\p{L}\p{N}]/gu, '');
    if (clean && !tags.includes(clean) && tags.length < MAX) tags.push(clean);
  };

  // 1-2. база: за цим нас шукають цілеспрямовано
  add('цінинапальне');
  add('пальне');

  // 3. тема — конкретне пальне
  if (fuel && FUEL_TAGS[fuel]) add(FUEL_TAGS[fuel]);
  else add('АЗС');

  // 4. географія має пріоритет над подією: вузький тег дає більше,
  //    ніж загальне «подорожчання», де конкуренція величезна
  if (region && REGION_TAGS[region]) {
    add(REGION_TAGS[region][0]);
  } else if (news) {
    add('новини');
  } else if (change !== undefined && Math.abs(change) >= 0.3) {
    add(change > 0 ? 'подорожчання' : 'здешевлення');
  } else {
    add('АЗС');
  }

  // 5. країна — завжди останній
  add('Україна');

  return tags.map(t => '#' + t).join(' ');
}

// Прифронтові області не тегаємо: аудиторії там мало, ціни нетипові
// (Донецька — 100+ грн, це логістика війни, а не ринок), а тема надто
// чутлива, щоб тягнути її в маркетинговий тег. Так само вони виключені
// з карти EV-зарядок.
const SKIP_REGIONS = new Set(['Донецька', 'Луганська', 'Херсонська', 'Запорізька']);

/** Область, яка «робить сюжет»: найдешевша або найдорожча — про неї й тег. */
export function standoutRegion(regionAvg, fuel = 'dp') {
  const list = Object.entries(regionAvg ?? {})
    .filter(([name, p]) => p?.[fuel] !== undefined && !SKIP_REGIONS.has(name))
    .sort((a, b) => a[1][fuel] - b[1][fuel]);
  if (list.length < 5) return null;

  const [cheapName, cheapP] = list[0];
  const [dearName, dearP] = list.at(-1);
  const mid = list[Math.floor(list.length / 2)][1][fuel];

  // беремо ту, що сильніше відірвалась від середини — там і сюжет
  const cheapGap = mid - cheapP[fuel];
  const dearGap = dearP[fuel] - mid;
  return dearGap > cheapGap ? dearName : cheapName;
}
