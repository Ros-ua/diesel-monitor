// Підбір хештегів під зміст поста.
//
// Чому не фіксований набір: за однаковими загальними тегами (#пальне) ми тонемо
// серед тисяч постів. Вузький тег (#Житомирщина) має менше конкуренції — там
// реально потрапити в топ і зібрати перегляди від людей, які нас не знають.
//
// Instagram із грудня 2025 радить ДО 5 хештегів — більше виглядає як спам
// і охоплення ріже. Тому рівно 5: база + тема + географія/подія.
//
// Геомітки (location_id) поставити не можемо: в Instagram API with Instagram
// Login немає пошуку локацій (перевірено 11.08.2026), тож область позначаємо
// саме хештегом.

// Область → теги. Дві форми: місто (його шукають частіше) і область.
