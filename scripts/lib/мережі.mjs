/**
 * Рішення про карту мереж: брати свіжу чи лишити попередню — і під якою датою.
 *
 * ⚠️ Дві беди, обидві мовчазні, обидві підтверджені розбором 12.09.2026.
 *
 * 1. ОДНА ВЦІЛІЛА МЕРЕЖА вважалася успішним збором. parsePriceTable кидає
 *    помилку лише тоді, коли не вціліло НІЧОГО; якщо верстка поїхала і
 *    розібрався один рядок із тридцяти шести — цей один мовчки заміняв усю
 *    карту. У знімку не лишалося жодної ознаки неповноти: ні числа мереж, ні
 *    попередження. Сайт показував би одну мережу як «усі ціни по Україні».
 *
 * 2. ПОПЕРЕДНЯ КАРТА лягала під СЬОГОДНІШНЬОЮ датою. Коли свіжої карти немає,
 *    брали вчорашню — і це правильно, бо інакше зникають сторінки мереж. Але
 *    записували її під сьогоднішніми `date` і `collectedAt`, без позначки
 *    давності: людина бачила вчорашні ціни, підписані сьогоднішнім числом.
 *    Для матриці «область × мережа» така позначка була (breakdownDate), а для
 *    мереж — ні.
 *
 * Функція чиста: ні мережі, ні файлів. Саме тому її можна перевірити пробами,
 * а рішення не тонуло всередині збирача.
 */

/** Нижче цього числа мереж порівняння на обвал не має сенсу. */
const МІНІМУМ_ДЛЯ_ПОРІВНЯННЯ = 4;

/**
 * @param {object} о
 * @param {object|null} о.свіжі          щойно розібрана карта мереж
 * @param {object|null} о.попередні      карта з попереднього знімка
 * @param {string} о.дата                дата даних цього збору
 * @param {string|null} [о.попередняДата] дата, коли попередню карту зібрали
 */
export function вибратиМережі({ свіжі, попередні, дата, попередняДата = null }) {
  const було = попередні ? Object.keys(попередні).length : 0;
  const стало = свіжі ? Object.keys(свіжі).length : 0;

  // ⚠️ Обвал — це коли карта схудла БІЛЬШ НІЖ УДВІЧІ. Звичайне коливання так не
  // виглядає: мережа зникає зі зведення Мінфіну час від часу, і 36 → 35 має
  // проходити спокійно. А от 36 → 1 означає, що поїхала верстка, і вірити
  // такому збору не можна.
  const обвал = було >= МІНІМУМ_ДЛЯ_ПОРІВНЯННЯ && стало > 0 && стало * 2 < було;

  const взяти = свіжі && !обвал ? свіжі : null;

  return {
    мережі: взяти ?? попередні ?? null,
    свіжі: !!взяти,
    обвал,
    було,
    стало,
    // Дата, КОЛИ карту справді зібрали, а не коли записали файл.
    дата: взяти ? дата : попередняДата,
  };
}
