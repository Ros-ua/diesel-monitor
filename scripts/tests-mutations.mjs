function прогін(корінь, сюїта = 'tests-parser.mjs') {
  try {
    const out = execFileSync(process.execPath, [path.join(корінь, сюїта)],
      { encoding: 'utf8', stdio: 'pipe', timeout: 300000 });
    return { впало: false, текст: out };
  } catch (e) {
    return { впало: true, текст: String(e.stdout ?? '') + String(e.stderr ?? '') };
  }
}

function накопії(робота) {
  const корінь = mkdtempSync(path.join(tmpdir(), 'diesel-mut-'));
  try {
    cpSync(SCRIPTS, корінь, { recursive: true });
    return робота(корінь);
  } finally {
    rmSync(корінь, { recursive: true, force: true });
  }
}

// Спершу переконуємось, що на ЦІЛІЙ копії все зелене — інакше міряти нічим.
//
// ⚠️ Червоний набір НЕ зупиняє весь прогін, але й не прощається: його підсадки
// лишаються НЕВИМІРЯНИМИ, і прогін через це провалюється. Раніше перший же
// червоний набір валив усе — і підсадки решти наборів не міряв НІХТО, хоча
// вони самі по собі справні. 20.09.2026 так і вийшло: tests-parser.mjs був
// червоний ще до правки, і разом із ним мовчки випали всі інші.
const хворі = new Set();
for (const сюїта of ['tests-parser.mjs', 'tests-collect.mjs', 'tests-geo.mjs']) {
  const базовий = накопії(к => прогін(к, сюїта));
  if (базовий.впало) {
    хворі.add(сюїта);
    console.log('❌ на цілій копії ' + сюїта + ' вже червоні — його підсадки не виміряні');
    console.log(базовий.текст.trim().split('\n').slice(-3).join('\n'));
  }
}
if (!хворі.size) console.log('ціла копія: усі проби зелені (розбір + наскрізні + GEO)');
console.log('');

let спіймано = 0;
let невиміряно = 0;
for (const п of ПІДСАДКИ) {
  if (хворі.has(п.сюїта ?? 'tests-parser.mjs')) {
    невиміряно++;
    console.log(`⚪ ${п.імя}\n     стереже: «${п.стереже}» — НЕ ВИМІРЯНО: набір ${п.сюїта ?? 'tests-parser.mjs'} червоний і без підсадки`);
    continue;
  }
  const р = накопії(корінь => {
    const ціль = path.join(корінь, п.файл);
    // ⚠️ Переводи рядків нормалізуємо. Git віддає файли з CRLF (core.autocrlf),
    // а якорі підсадок написані з LF — і БАГАТОРЯДКОВІ якорі перестають
    // збігатися. Спіймано 12.09 одразу після rebase: було 17 з 17, стало 14,
    // і три підсадки мовчки «не застосувалися». Однорядкові при цьому
    // збігалися далі, тож біда виглядала вибірковою і тим підступнішою.
    const текст = readFileSync(ціль, 'utf8').replace(/\r\n/g, '\n');
    const скільки = текст.split(п.було).length - 1;
    if (скільки !== 1) return { якір: скільки };
    // ⚠️ Заміна ФУНКЦІЄЮ, а не рядком. Рядок-заміна у String.replace тлумачить
    // `$&`, `$1`, `` $` `` як спецпослідовності — і підсадка, у тексті якої є
    // `$&` (а це будь-яка правка регулярки), вписала б у копію не себе, а
    // знайдений шматок. Код копії ставав битим, набір падав із синтаксичною
    // помилкою, і прогін зараховував підсадку як спійману «бо все впало» —
    // слабке доказування на порожньому місці (спіймано 20.09.2026, §4а).
    writeFileSync(ціль, текст.replace(п.було, () => п.стало));
    return прогін(корінь, п.сюїта);
  });

  if (р.якір !== undefined) {
    console.log(`⚠️  ${п.імя}: якір трапляється ${р.якір} разів — підсадку НЕ застосовано`);
    continue;
  }

  // Мало «стало червоно»: шукаємо рядок ПОТРІБНОЇ проби.
  const рядок = р.текст.split('\n').find(s => s.includes(п.стереже));
  const потрібнаЧервона = рядок ? рядок.includes('❌') : false;
  const впало = р.впало && !рядок;      // проба до друку не дійшла — теж спіймано
  const ок = потрібнаЧервона || впало;
  if (ок) спіймано++;
  const як = потрібнаЧервона ? 'проба почервоніла'
    : впало ? 'збір впав з помилкою'
      : 'НІХТО НЕ ПОМІТИВ';
  console.log(`${ок ? '✅' : '❌'} ${п.імя}\n     стереже: «${п.стереже}» — ${як}`);
}

console.log(`\nпідсадок спіймано: ${спіймано} з ${ПІДСАДКИ.length}`);
if (невиміряно) console.log(`з них НЕ ВИМІРЯНО: ${невиміряно} (червоний набір на цілій копії)`);
process.exit(спіймано === ПІДСАДКИ.length ? 0 : 1);
